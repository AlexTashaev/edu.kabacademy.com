if '--sql' in sys.argv:
    i = sys.argv.index('--sql')
    bookid, cmid = int(sys.argv[i + 1]), int(sys.argv[i + 2])
    NOW = int(time.time())
    def hx(s):
        return '0x' + binascii.hexlify(s.encode('utf-8')).decode()
    def q(s):
        return "'" + s.replace(chr(92), chr(92) * 2).replace("'", "''") + "'"
    NAME = 'Первоисточники к уроку 2 – Бааль Сулам и Рабаш о желании'
    sql = ['SET NAMES utf8mb4;', 'START TRANSACTION;']
    sql.append("UPDATE mdl_book SET name=%s, intro='', timemodified=%d WHERE id=%d;" % (q(NAME), NOW, bookid))
    sql.append("DELETE FROM mdl_book_chapters WHERE bookid=%d;" % bookid)
    for n, (title, html) in enumerate(CHAPTERS, 1):
        sql.append("INSERT INTO mdl_book_chapters (bookid,pagenum,subchapter,title,content,contentformat,hidden,timecreated,timemodified,importsrc) VALUES (%d,%d,0,%s,%s,1,0,%d,%d,'');" % (bookid, n, q(title), hx(html), NOW, NOW))
    sql.append("UPDATE mdl_course_modules SET visible=1, visibleold=1 WHERE id=%d AND instance=%d;" % (cmid, bookid))
    sql.append("UPDATE mdl_course SET cacherev=cacherev+1 WHERE id=236;")
    sql += ['COMMIT;', "SELECT id,pagenum,title,LENGTH(content) clen FROM mdl_book_chapters WHERE bookid=%d ORDER BY pagenum; SELECT id,visible FROM mdl_course_modules WHERE id=%d;" % (bookid, cmid)]
    open('l2book.sql', 'w', encoding='utf-8', newline='\n').write('\n'.join(sql) + '\n')
    print('sql bytes', os.path.getsize('l2book.sql'))
