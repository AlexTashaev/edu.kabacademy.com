GRAY = '#7A7A7A'

def kicker(t):
    return '<div class="kab-kicker">%s</div>\n' % t

def h(t):
    return '<div class="kab-h">%s</div>\n' % t

def p(t):
    return '<p>%s</p>\n' % t

def note(t):
    return '<div class="kab-note">%s</div>\n' % t

def excerpt(quote, source, purple=False):
    """quote: list of paragraphs (already with « »); source: attribution without links."""
    cls = 'kab-quote kab-quote--purple' if purple else 'kab-quote'
    body = ''.join('<p>%s</p>\n' % q for q in quote)
    src = ('<div style="text-align: right; font-size: 13.5px; line-height: 1.5; color: %s; margin-top: 10px;">— %s</div>\n' % (GRAY, source))
    return '<div class="%s">\n%s%s</div>\n' % (cls, body, src)

def page(inner):
    return '<div class="kab-page">\n%s</div>\n' % inner

